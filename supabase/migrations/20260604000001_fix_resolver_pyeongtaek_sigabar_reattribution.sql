-- 데이터 정정: 레솔베르 평택점 사업자변경(2025-09-25) 관련 출고 1건 재귀속.
--
-- 배경: (주)레솔베르 평택점(30204) 사업자가 2025-09-25 변경되어 이후 거래는
--   레솔베르 시가바(30278) / 레솔베르 시가바 평택점(32464)로 이관됨.
--   그런데 2026-03-12 출고(D700097 하이볼 글라스 qty12, 166,320)가 스마트 업로드 매칭에서
--   옛 코드 30204(평택점)로 잘못 들어가, 비활성 평택점에 166,320 미수가 잡히고
--   공식 매출처원장(30204 누계 679,800 완납)과 어긋남.
--
-- 조치: 해당 1건을 활성 코드 32464(레솔베르 시가바 평택점)로 이동.
--   결과: 30204 미수 0(원장 일치), 32464 는 시가바 평택점 결제 흐름과 정합
--   (32464 잔액 -166,320 은 고객 선입금분으로 정상).
--
-- 업무키로 타깃(멱등). 라이브 적용 완료분의 박제.
UPDATE glass_shipments
SET client_code = '32464', client_name = '레솔베르 시가바 평택점'
WHERE client_code = '30204'
  AND ship_date = '2026-03-12'
  AND item_no = 'D700097'
  AND total_amount = 166320;
